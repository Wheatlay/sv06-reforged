// Generate the status-screen icon bitmaps for the firmware from the approved mockup.
// Usage (project root): node tools/gen_status_bitmaps.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const A = JSON.parse(fs.readFileSync(path.join(root, 'mockup/lcd_assets.json'), 'utf8'));
const L = require('../mockup/lcd.js');

const I = L.stockIcons(A);
const icons = {
  nozzle: I.nozzle, nozzle_on: I.nozzleOn, bed: I.bed, bed_on: I.bedOn,
  fan0: I.fan[0], fan1: I.fan[1], moon: L.MOON16,
};

let out = '// Generated by tools/gen_status_bitmaps.js from mockup/lcd.js + lcd_assets.json. Do not edit by hand.\n#pragma once\n\n';
for (const [name, rows] of Object.entries(icons)) {
  const w = rows[0].length, bw = Math.ceil(w / 8), N = name.toUpperCase();
  out += `#define SV06_${N}_W ${w}\n#define SV06_${N}_H ${rows.length}\n#define SV06_${N}_BW ${bw}\n`;
  out += `const unsigned char sv06_${name}_bmp[] PROGMEM = {\n`;
  for (const r of rows) {
    const p = r.padEnd(bw * 8, '0');
    const bytes = [];
    for (let i = 0; i < bw; i++) bytes.push('B' + p.slice(i * 8, i * 8 + 8));
    out += `  ${bytes.join(',')}, // ${r.replace(/0/g, '.').replace(/1/g, '#')}\n`;
  }
  out += '};\n\n';
}
fs.writeFileSync(path.join(root, 'firmware/Marlin/src/lcd/dogm/status_screen_sv06_bitmaps.h'), out);
console.log(Object.entries(icons).map(([n, r]) => `${n} ${r[0].length}x${r.length}`).join(', '));
